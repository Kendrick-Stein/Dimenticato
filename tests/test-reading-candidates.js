#!/usr/bin/env node
'use strict';
const assert = require('assert'), fs = require('fs'), path = require('path');
const { validateQueue, validateSources, matchesPrefix } = require('../scripts/validate_reading_candidates');
const root = path.resolve(__dirname, '..');
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const registry = read('data/reading/sources.json'), queue = read('editorial/reading/candidates.json');
const articleFiles = fs.readdirSync(path.join(root, 'data/reading/articles')).filter(file => file.endsWith('.json'));
const articles = articleFiles.map(file => read('data/reading/articles/' + file));
const clone = object => JSON.parse(JSON.stringify(object));
let passed = 0;
function test(fn) { fn(); passed++; }
function invalid(change, message, sources = registry, published = articles) {
  const copy = clone(queue); change(copy);
  test(() => assert(validateQueue(copy, sources, published).some(error => error.includes(message)), 'Expected ' + message + ': ' + validateQueue(copy, sources, published).join('; ')));
}
test(() => assert.deepEqual(validateQueue(queue, registry, articles), []));
test(() => assert.deepEqual(validateSources(registry), []));
test(() => assert(validateSources(null).length > 0));
test(() => assert(validateQueue(null, registry).length > 0));
test(() => assert(validateQueue(queue, {schema:1,sources:null}).length > 0));
invalid(q => q.candidates.push(clone(q.candidates[0])), 'unique safe candidate id');
invalid(q => q.candidates[0] = null, 'candidate must be an object');
invalid(q => q.candidates[0].category = 'random', 'supported category');
invalid(q => q.candidates[0].topics = ['x','x'], 'unique topic');
invalid(q => q.candidates[0].level = 'advanced', 'CEFR');
invalid(q => q.candidates[0].sourcePublishedAt = '2026-02-30', 'publication and collection dates');
invalid(q => q.candidates[0].sourcePublishedAt = '2026-10-11', 'future');
invalid(q => q.candidates[0].collectedAt = '2026-10-11', 'future');
invalid(q => q.candidates[0].status = 'published', 'published is forbidden');
invalid(q => q.candidates[0].verification.fullText.sentences = [{text:'Full article',zh:'译文'}], 'unexpected nested metadata');
invalid(q => q.candidates[0].verification.fullText.notes = {body:'Raw text'}, 'metadata type');
invalid(q => { const copy = clone(q.candidates[0]); copy.id += '-duplicate'; copy.sourceUrl += '?utm_source=newsletter'; q.candidates.push(copy); }, 'duplicate candidate source URL');
invalid(q => q.candidates[0].sentences = [{text:'Draft',zh:'草稿'}], 'unexpected candidate field');
invalid(q => q.candidates[0].verification.readyForPublication = true, 'never publishable');
invalid(q => q.candidates[0].verification.workflowStage = 'published', 'no published stage');
invalid(q => q.candidates[0].verification.workflowStage = 'ready', 'completed review');
invalid(q => q.candidates[0].verification = null, 'evidence object');
invalid(q => q.candidates[0].verification.fullText.read = false, 'inspected full text');
invalid(q => q.candidates[0].verification.fullText.url = 'https://example.org', 'inspected full text');
invalid(q => q.candidates[0].verification.originalDate.verified = false, 'originalDate verification');
invalid(q => q.candidates[0].verification.nativeLanguage.evidence = '', 'nativeLanguage verification');
invalid(q => q.candidates[0].verification.rights.adaptationAllowed = false, 'rights must be verified');
invalid(q => q.candidates[0].verification.rights.evidenceUrls = ['http://bad.test'], 'rights evidence URLs');
invalid(q => q.candidates[0].verification.rights.attributionRequirements = [], 'attribution requirements');
invalid(q => q.candidates[0].verification.rights.exclusions = [], 'rights exclusions');
invalid(q => q.candidates[0].verification.freshness.ageDays++, 'age must derive');
invalid(q => q.candidates[0].verification.freshness.bucket = 'archive', 'bucket must match');
invalid(q => q.candidates[0].registrySourceId = 'not-registered', 'reviewed registry');
invalid(q => q.candidates[0].language = 'fr', 'language must belong');
invalid(q => q.candidates[0].sourceUrl = 'https://www.ingv.it.evil.test/stampa-urp/ufficio-stampa/comunicati-stampa/a', 'outside registered');
invalid(q => q.candidates[0].sourceUrl = 'https://user:password@www.ingv.it/stampa-urp/ufficio-stampa/comunicati-stampa/a', 'credential-free');
const byPublisher = queue.candidates.findIndex(c => c.verification.publisher);
if (byPublisher >= 0) invalid(q => q.candidates[byPublisher].verification.publisher.names = ['Wrong agency'], 'publisher must match');
const sameSource = {id:'published-source',lang:queue.candidates[0].language,source:{url:queue.candidates[0].sourceUrl}};
invalid(() => {}, 'already-published source', registry, [sameSource]);
invalid(q => { q.candidates[0].sourceUrl += '?utm_source=newsletter'; q.candidates[0].verification.fullText.url = q.candidates[0].sourceUrl; }, 'already-published source', registry, [sameSource]);
invalid(q => q.candidates[0].linkToArticleId = 'unrelated', 'separately published', registry, [sameSource]);
const promoted = clone(queue); promoted.candidates[0].linkToArticleId = sameSource.id;
test(() => assert.deepEqual(validateQueue(promoted, registry, [sameSource]), [], 'link records separate editorial publication, not an automatic promotion'));
test(() => assert(matchesPrefix('https://example.org/news/item', 'https://example.org/news/')));
test(() => assert(!matchesPrefix('https://example.org/newsletter/item', 'https://example.org/news')));
test(() => assert(!matchesPrefix('https://example.org.evil.test/news/item', 'https://example.org/news')));
test(() => assert(!matchesPrefix('http://example.org/news/item', 'https://example.org/news')));
const malformedPublisher = clone(registry); malformedPublisher.sources[0].requiredPublisherNames = 'wrong';
test(() => assert(validateQueue(queue, malformedPublisher).some(error => error.includes('publisher names')), 'malformed registry returns validation errors instead of throwing'));
const sourceWithoutReview = clone(registry); sourceWithoutReview.sources[0].articleReviewRequired = false;
test(() => assert(validateSources(sourceWithoutReview).some(error => error.includes('must remain true'))));
const articleSchema = read('docs/reading-article.schema.json'), queueSchema = read('docs/reading-candidates.schema.json');
test(() => assert.deepEqual(queueSchema.properties.candidates.items.properties.category.enum, articleSchema.properties.category.enum));
const catalogIds = new Set(read('data/reading/index.json').articles.map(article => article.id));
queue.candidates.forEach(candidate => test(() => assert(!catalogIds.has(candidate.id), 'intake does not become a public article')));
console.log('Reading candidates OK: ' + passed + ' passed, 0 failed');

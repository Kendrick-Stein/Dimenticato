#!/usr/bin/env node
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('assert');
const { createWindow } = require('./dom-shim');
const root = path.resolve(__dirname, '..');
let passed = 0;
const ok = (v, message) => { assert.ok(v, message); passed++; };
function setup(storage) {
  const w = createWindow();
  if (storage) w.localStorage = storage;
  w.MutationObserver = class { observe() {} };
  w.document.readyState = 'loading';
  w.document.body.innerHTML = fs.readFileSync(path.join(root, 'index.html'), 'utf8').match(/<body[^>]*>([\s\S]*?)<\/body>/)[1];
  w.document.body.setAttribute('data-language', 'italian');
  w.getActiveLanguage = () => w.document.body.getAttribute('data-language');
  w.voiceList = []; w.calls = []; w.voiceEvents = {}; w.messages = [];
  w.speechSynthesis = {
    getVoices: () => w.voiceList, addEventListener: (name, fn) => { w.voiceEvents[name] = fn; },
    cancel() {}, speak(u) { w.calls.push(u); }
  };
  const context = vm.createContext(w);
  for (const f of ['lib/utils.js', 'lib/languages.js', 'lib/storage.js']) vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), context);
  w.Shell = { current: () => 'settingsScreen' };
  w.QuizEngine = { renderDifficultyToggle: () => '', renderDirectionToggle: () => '' };
  w.Vocab = { headword: x => x.word };
  let src = fs.readFileSync(path.join(root, 'app.js'), 'utf8').replace('  global.App = App;', '  global.App = App; global.VoiceTest = {renderSettings, renderVoiceSettings, bind};');
  vm.runInContext(src, context);
  w.App.toast = message => w.messages.push(message);
  return w;
}
const voice = (name, lang, extras = {}) => Object.assign({name, lang, voiceURI:name, localService:true}, extras);
let w = setup(), S = w.Speaker;
const basic = voice('Basic', 'it-IT'), enhanced = voice('Enhanced', 'it-IT'), foreign = voice('Google French', 'fr-FR');
w.voiceList = [basic, foreign, enhanced, voice('Google German', 'de-DE'), voice('English Natural', 'en-US')];
for (const [code, tag] of [['it','it-IT'],['fr','fr-FR'],['de','de-DE'],['en','en-US']]) {
  ok(S.available(code).every(v => v.lang === tag), code + ' voices filtered');
  ok(S.speak('test', code) && w.calls.at(-1).lang === tag, code + ' speaks matched language');
}
ok(S.selection('it').voice === enhanced, 'name heuristic ranks enhanced in exact locale');
w.voiceList.push(voice('Premium Swiss', 'it-CH'));
ok(S.selection('it').voice === enhanced, 'exact locale precedes heuristic');
ok(S.setPreference('italian', S.id(basic)), 'save with legacy language name');
ok(S.selection('it').voice === basic, 'explicit choice overrides heuristic');
ok(S.speak('test','it') && w.calls.at(-1).voice === basic, 'explicit voice used');
ok(S.preference('fr') === '', 'language preference isolated');
ok(!S.setPreference('it', S.id(foreign)), 'cross-language choice rejected');
ok(!S.setPreference('it', 'not a voice'), 'invalid choice rejected');
let fresh = setup(w.localStorage); fresh.voiceList = w.voiceList.slice();
ok(fresh.Speaker.selection('it').voice.name === 'Basic', 'choice persists after reload');
w.voiceList = [enhanced];
ok(S.selection('it').missing && S.selection('it').voice === enhanced, 'removed choice falls back within language');
ok(S.preference('it') === S.id(basic), 'missing preference preserved for returning voice');
w.voiceList = [foreign]; const before = w.calls.length;
ok(S.speak('test','it') === false && w.calls.length === before, 'no matching voice never invokes synthesis');
ok(w.messages.at(-1).includes('当前语言暂无可用语音'), 'manual call surfaces missing voice');
let error; S.speak('test','it', e => {error=e;});
ok(error === 'no-voice' && w.messages.length === 1, 'callback handles error without duplicate toast');
w.voiceList = [enhanced];
S.speak('old','it', () => {throw new Error('stale error');}); const old = w.calls.at(-1);
S.cancel(); old.onerror({error:'network'}); ok(true, 'stale asynchronous error ignored');
S.speak('new','it'); w.calls.at(-1).onerror({error:'network'}); ok(w.messages.length === 2, 'manual async error surfaced');
S.speak('new','it'); w.calls.at(-1).onerror({error:'interrupted'}); ok(w.messages.length === 2, 'interruption silent');
const getVoices = w.speechSynthesis.getVoices; w.speechSynthesis.getVoices = () => { throw Error('API unavailable'); };
ok(S.speak('test','it', e => {error=e;}) === false && S.available('it').length === 0, 'voice enumeration failure safe');
w.speechSynthesis.getVoices = getVoices;
const ls=w.localStorage, D=w.DimStorage;
ls.setItem('dimenticato_it_mastered','["casa"]');
ls.setItem('dimenticato_it_daily_stats','{"2026-01-01":{"attempts":1}}');
ls.setItem('dimenticato_fr_mastered','["maison"]');
const set=ls.setItem; let pruned=0; D._pruneDailyStats=()=>{pruned++;return true;};
ls.setItem=()=>{throw Error('quota');};
ok(!S.setPreference('it', S.id(enhanced)), 'quota failure reported');
ok(pruned===0 && ls.getItem('dimenticato_it_daily_stats').includes('2026-01-01'), 'optional preference never prunes learning statistics');
ok(S.preference('it')===S.id(basic), 'failure retains original preference'); ls.setItem=set;
const exported=D.exportAll();
const restored=setup(); restored.voiceList=[basic,enhanced]; restored.DimStorage.importAll(exported,{mode:'overwrite'});
ok(restored.Speaker.preference('it')===S.id(basic), 'export/import roundtrip retains preference');
ok(restored.localStorage.getItem('dimenticato_it_mastered')==='["casa"]', 'roundtrip retains mastery');
D.reset({scope:'it'}); ok(S.preference('it')===S.id(basic), 'language progress reset preserves voice');
ok(ls.getItem('dimenticato_fr_mastered')==='["maison"]', 'language reset leaves other language untouched');
D.reset({scope:'all'}); ok(S.preference('it')===S.id(basic), 'all progress reset preserves voice');
D.importAll({version:'1.0',data:{masteredWords:'["libro"]'}},{mode:'overwrite'});
ok(S.preference('it')===S.id(basic), 'old backup without voice retains preference');
ls.setItem('dimenticato_it_voice','malformed'); ok(S.selection('it').missing && S.selection('it').voice===enhanced, 'malformed imported voice safely falls back');
ok(S.setPreference('it','') && S.preference('it')==='', 'automatic choice clears preference');
// Real app rendering and event handlers. The synth is the only simulated device API.
w.voiceList=[]; w.VoiceTest.renderSettings(); w.VoiceTest.bind();
const select=w.document.getElementById('settingsVoice'), status=w.document.getElementById('settingsVoiceStatus'), preview=w.document.getElementById('settingsVoicePreview');
ok(select.disabled && preview.disabled, 'no-voice settings disables controls');
ok(status.textContent.includes('暂无可用语音'), 'no-voice settings explains why');
w.document.activeElement=select; w.voiceList=[basic,enhanced]; w.voiceEvents.voiceschanged();
ok(w.document.getElementById('settingsVoice')===select && w.document.activeElement===select, 'late voices keep select DOM and focus');
ok(!select.disabled && !preview.disabled, 'late voices enable controls');
select.value=S.id(basic); w.document.getElementById('settingsPrefs').dispatchEvent({type:'change',target:select});
ok(S.preference('it')===S.id(basic) && status.textContent.includes('Basic'), 'real change handler saves and updates status');
w.document.getElementById('settingsPrefs').dispatchEvent({type:'click',target:preview});
ok(w.calls.at(-1).voice===basic && w.calls.at(-1).text==='Per non dimenticare.', 'preview uses active language and explicit voice');
ls.setItem('dimenticato_it_voice', S.id(enhanced)); w.dispatchEvent({type:'storage',key:'dimenticato_it_voice'});
ok(select.value===S.id(enhanced), 'other tab preference change updates controls');
ls.setItem=()=>{throw Error('quota');}; select.value=S.id(basic); w.document.getElementById('settingsPrefs').dispatchEvent({type:'change',target:select});
ok(select.value===S.id(enhanced) && status.textContent.includes('未能保存'), 'failed UI save restores actual preference and explains failure'); ls.setItem=set;
w.voiceList=[voice('<script>fake</script>', 'it-IT')]; w.voiceEvents.voiceschanged();
ok(!select.innerHTML.includes('<script>') && select.innerHTML.includes('&lt;script&gt;'), 'voice labels escaped');
w.document.body.setAttribute('data-language','french'); w.voiceList=[foreign]; w.VoiceTest.renderSettings();
ok(w.document.getElementById('settingsVoice').value==='' && w.document.getElementById('settingsVoiceStatus').textContent.includes('French'), 'language switch uses independent preference');
const synth=w.speechSynthesis; delete w.speechSynthesis; w.VoiceTest.renderVoiceSettings();
ok(w.document.getElementById('settingsVoiceStatus').textContent.includes('不支持朗读'), 'unsupported browser distinguished from missing language');
let unsupported; ok(!S.speak('test','fr', e=>unsupported=e) && unsupported==='unsupported', 'unsupported callback reason'); w.speechSynthesis=synth;
w.voiceList=[voice('British', 'en-GB'),voice('US', 'en-US')];
ok(S.setPreference('en', S.id(w.voiceList[0])) && S.speak('test','en') && w.calls.at(-1).lang==='en-GB', 'explicit region uses chosen voice locale');
const currentEn=S.preference('en'); D.importAll({keys:{dimenticato_en_voice:S.id(w.voiceList[1])}},{mode:'merge'});
ok(S.preference('en')===currentEn, 'merge import retains existing voice choice');
console.log(passed+' passed, 0 failed');

def select_entries(vocab: list[dict[str, Any]]) -> list[dict[str, Any]]:
    verb_lemmas = {str(e.get("german", "")).lower() for e in vocab if is_verb_entry(e)}
    by_word = {str(e.get("german", "")).lower(): e for e in vocab}
    seen: set[str] = set()
    candidates: list[dict[str, Any]] = []
    for word in MANDATORY:
        source = by_word.get(word) or {
            "german": word,
            "meaning": "",
            "chinese": "",
            "notes": "manual",
            "rank": 999999,
        }
        seen.add(word)
        candidates.append(source)
    for entry in vocab:
        word = str(entry.get("german", "")).lower()
        if word in seen or not is_verb_entry(entry):
            continue
        if looks_separable(word, verb_lemmas):
            continue
        try:
            parts_for(entry)
        except Exception:
            continue
        seen.add(word)
        candidates.append(entry)

    def sort_key(entry: dict[str, Any]) -> tuple[float, int, str]:
        word = str(entry["german"]).lower()
        return (-german_frequency(word, int(entry.get("rank") or 999999)), int(entry.get("rank") or 999999), word)

    selected = sorted(candidates, key=sort_key)[:TARGET_COUNT]
    if len(selected) < 250:
        raise RuntimeError(f"Only {len(selected)} high-confidence German verbs selected")
    return selected


def build() -> list[dict[str, Any]]:
    vocab = load_js_array(VOCAB_PATH, "GERMAN_VOCABULARY_DATA")
    selected = select_entries(vocab)
    entries: list[dict[str, Any]] = []
    for rank, entry in enumerate(selected, start=1):
        infinitive = str(entry["german"]).lower()
        parts = parts_for(entry)
        entries.append(
            {
                "rank": rank,
                "infinitive": infinitive,
                "frequency": german_frequency(infinitive, int(entry.get("rank") or 999999)),
                "english": clean_gloss(str(entry.get("meaning") or "")),
                "chinese": clean_gloss(str(entry.get("chinese") or entry.get("meaning") or "")),
                "tenses": build_tenses(infinitive, parts),
            }
        )
    return entries


def main() -> None:
    data = build()
    header = (
        "// Auto-generated by scripts/build_german_conjugations.py\n"
        f"// Source: data/german-vocabulary.js notes + wordfreq Zipf frequency; total entries: {len(data)}; "
        "schema mirrors data/conjugations-all-tenses.js; separable-prefix verbs are filtered unless explicit\n"
    )
    OUT_PATH.write_text(
        header
        + "const GERMAN_CONJUGATION_DATA = "
        + json.dumps(data, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(data)} entries to {OUT_PATH}")


if __name__ == "__main__":
    main()

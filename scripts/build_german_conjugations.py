def parts_for(entry: dict[str, Any]) -> Parts:
    word = str(entry["german"]).lower()
    if word in MANUAL:
        return MANUAL[word]
    if word in PRINCIPAL_OVERRIDES:
        third, pret, part, aux = PRINCIPAL_OVERRIDES[word]
        return Parts(
            present_from_third(word, third),
            preterite_forms_from_singular(pret),
            part,
            aux,
            "manual principal-parts override",
        )

    third, pret, part, parsed_aux = parse_notes(str(entry.get("notes", "")))
    present = present_from_third(word, third)
    preterite = preterite_forms_from_singular(pret or weak_preterite_from_infinitive(word))
    partizip_ii = part or regular_participle(word)

    aux: tuple[str, ...]
    if parsed_aux:
        aux = parsed_aux
    elif word in SEIN_AUX_VERBS or str(entry.get("notes", "")).strip().startswith("Vi") and word in SEIN_AUX_VERBS:
        aux = ("sein",)
    else:
        aux = ("haben",)
    confidence = "vocab principal parts" if pret or part or third else "weak regular rule"
    return Parts(present, preterite, partizip_ii, aux, confidence)


def forms(values: list[str]) -> dict[str, str]:
    return dict(zip(PERSONS, values, strict=True))


def tense(group: str, label: str, values: list[str]) -> dict[str, Any]:
    return {"type": "person", "group_label": group, "tense_label": label, "forms": forms(values)}


def single(group: str, label: str, values: list[str]) -> dict[str, Any]:
    return {"type": "single", "group_label": group, "tense_label": label, "forms": values}



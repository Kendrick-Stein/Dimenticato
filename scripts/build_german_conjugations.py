def load_js_array(path: Path, const_name: str) -> list[dict[str, Any]]:
    text = path.read_text(encoding="utf-8")
    match = re.search(rf"const\s+{re.escape(const_name)}\s*=\s*\[", text)
    if not match:
        raise ValueError(f"Could not find {const_name} in {path}")
    start = match.end() - 1
    depth = 0
    in_string = False
    escape = False
    for pos in range(start, len(text)):
        ch = text[pos]
        if in_string:
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0:
                return json.loads(text[start : pos + 1])
    raise ValueError(f"Could not parse array for {const_name} in {path}")


def normalize_spelling(text: str) -> str:
    replacements = {
        "muß": "muss",
        "Muß": "Muss",
        "gemußt": "gemusst",
        "wußte": "wusste",
        "gewußt": "gewusst",
        "läßt": "lässt",
        "vergißt": "vergisst",
        "daß": "dass",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text.strip()


def clean_gloss(text: str) -> str:
    text = re.sub(r"\b(?:Vi|Vt|V|Vr|Adv|Präp|Konj|Pron|Art)\b\.?", "", text)
    text = re.sub(r"\([^)]*\)", "", text)
    text = re.sub(r"\s+", " ", text).strip(" ;,")
    return text.split(";")[0].split("；")[0][:80]


def german_frequency(word: str, rank: int) -> float:
    if zipf_frequency:
        return round(float(zipf_frequency(word, "de")), 4)
    return round(max(0.0, 7.0 - rank / 5000), 4)


def is_verb_entry(entry: dict[str, Any]) -> bool:
    word = str(entry.get("german", "")).lower()
    notes = str(entry.get("notes", ""))
    if word in SKIP_WORDS:
        return False
    if not re.fullmatch(r"[a-zäöüß]+", word):
        return False
    if not (word.endswith("en") or word.endswith("n")):
        return False
    return bool(re.search(r"(^|[ /])V(?:i|t|r)?(?:[ /().]|$)", notes))


def looks_separable(word: str, verb_lemmas: set[str]) -> bool:
    if word in MANUAL:
        return False
    for prefix in SEPARABLE_PREFIXES:
        if word.startswith(prefix) and len(word) > len(prefix) + 4:
            rest = word[len(prefix) :]
            if rest in verb_lemmas or rest in MANUAL or rest in globals().get("PRINCIPAL_OVERRIDES", {}):
                return True
    return False


def infinitive_stem(infinitive: str) -> str:
    if infinitive.endswith("eln") or infinitive.endswith("ern"):
        return infinitive[:-1]
    if infinitive.endswith("en"):
        return infinitive[:-2]
    if infinitive.endswith("n"):
        return infinitive[:-1]
    raise ValueError(f"Unsupported infinitive {infinitive}")


def needs_e(stem: str) -> bool:
    if stem.endswith(("d", "t")):
        return True
    return bool(re.search(r"(chn|ffn|gn|tm|dm)$", stem))


def is_sibilant(stem: str) -> bool:
    return stem.endswith(("s", "ss", "ß", "z", "x"))


def regular_present(infinitive: str) -> list[str]:
    if infinitive.endswith("eln"):
        stem = infinitive[:-1]
        ich = stem[:-2] + "le" if stem.endswith("el") else stem + "e"
        return [ich, stem + "st", stem + "t", infinitive, stem + "t", infinitive]
    if infinitive.endswith("ern"):
        stem = infinitive[:-1]
        return [stem + "e", stem + "st", stem + "t", infinitive, stem + "t", infinitive]

    stem = infinitive_stem(infinitive)
    if needs_e(stem):
        du = stem + "est"
        er = stem + "et"
        ihr = stem + "et"
    elif is_sibilant(stem):
        du = stem + "t"
        er = stem + "t"
        ihr = stem + "t"
    else:
        du = stem + "st"
        er = stem + "t"
        ihr = stem + "t"
    return [stem + "e", du, er, infinitive, ihr, infinitive]


def present_from_third(infinitive: str, third: str | None) -> list[str]:
    forms = regular_present(infinitive)
    if not third or third == forms[2]:
        return forms
    third = normalize_spelling(third)
    forms[2] = third
    if third.endswith("et"):
        forms[1] = third[:-1] + "st"
    elif third.endswith("t"):
        if infinitive_stem(infinitive).endswith("t"):
            forms[1] = third + "st"
        else:
            changed_stem = third[:-1]
            forms[1] = changed_stem + ("t" if is_sibilant(changed_stem) else "st")
    else:
        forms[1] = third + "st"
    return forms


def regular_participle(infinitive: str) -> str:
    stem = infinitive_stem(infinitive)
    suffix = "et" if needs_e(stem) else "t"
    if infinitive.endswith("ieren"):
        return infinitive[:-2] + "t"
    if infinitive.startswith(INSEPARABLE_PREFIXES) or infinitive.startswith(("über", "unter")):
        return stem + suffix
    return "ge" + stem + suffix


def weak_preterite_from_infinitive(infinitive: str) -> str:
    stem = infinitive_stem(infinitive)
    return stem + ("ete" if needs_e(stem) else "te")


def preterite_forms_from_singular(singular: str) -> list[str]:
    singular = normalize_spelling(singular)
    if singular.endswith("te"):
        return [singular, singular + "st", singular, singular + "n", singular + "t", singular + "n"]
    du_suffix = "est" if singular.endswith(("d", "t", "s", "ß", "z", "x")) else "st"
    ihr_suffix = "et" if singular.endswith(("d", "t")) else "t"
    return [singular, singular + du_suffix, singular, singular + "en", singular + ihr_suffix, singular + "en"]


def parse_notes(notes: str) -> tuple[str | None, str | None, str | None, tuple[str, ...] | None]:
    notes = normalize_spelling(notes)
    match = re.search(r"\(([^)]{3,120})\)", notes)
    if not match:
        return None, None, None, None
    inside = match.group(1)
    if inside.strip().startswith("+"):
        return None, None, None, None
    if not re.search(r"[a-zäöüß]{2,}", inside, re.I):
        return None, None, None, None
    inside = re.sub(r"\b(?:Vt|Vi|Vr|V)\b.*$", "", inside).strip()
    inside = inside.replace(",,", ",")
    aux: tuple[str, ...] | None = None

    if "ist/hat" in inside or "hat/ist" in inside:
        aux = ("sein", "haben")
        inside = inside.replace("ist/hat", "").replace("hat/ist", "")
    elif re.search(r"\bist\b", inside):
        aux = ("sein",)
        inside = re.sub(r"\bist\b", "", inside)
    elif re.search(r"\bhat\b", inside):
        aux = ("haben",)
        inside = re.sub(r"\bhat\b", "", inside)

    pieces = [p.strip(" ,;") for p in inside.split(",") if p.strip(" ,;")]
    third: str | None = None
    preterite: str | None = None
    participle: str | None = None

    if len(pieces) >= 3:
        third, preterite, participle = pieces[0], pieces[1], pieces[2]
    elif len(pieces) == 2:
        first, second = pieces
        if second.startswith(("ge", "be", "er", "ver", "zer", "ent", "emp")) or second.endswith(("en", "t")):
            preterite, participle = first, second
        else:
            third, preterite = first, second
    elif len(pieces) == 1:
        tokens = pieces[0].split()
        if len(tokens) >= 2:
            preterite, participle = tokens[0], tokens[1]

    def cleanup(value: str | None) -> str | None:
        if not value:
            return None
        value = re.sub(r"\s+", " ", value).strip()
        value = re.sub(r"^(?:hat|ist)\s+", "", value)
        value = value.split("/")[0] if "/" in value and not value.startswith("ge") else value
        value = value.replace(" ", "")
        return normalize_spelling(value)

    return cleanup(third), cleanup(preterite), cleanup(participle), aux



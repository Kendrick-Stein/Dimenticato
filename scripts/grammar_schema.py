def read(code, path=None):
    """Load a grammar data file through Node (it is a classic script)."""
    path = path or os.path.join(ROOT, LANGS[code]['file'])
    script = (
        "const vm=require('vm'),fs=require('fs');"
        "const ctx={module:undefined};ctx.globalThis=ctx;vm.createContext(ctx);"
        "vm.runInContext(fs.readFileSync(process.argv[1],'utf8'),ctx);"
        "process.stdout.write(JSON.stringify(ctx.DIM_DATA.grammar[process.argv[2]]));"
    )
    out = subprocess.check_output(['node', '-e', script, path, code])
    return json.loads(out.decode('utf-8'))


LINK_RE = re.compile(r'(\]\(\s*<?)([^)\s>]+)(>?(?:\s+"[^"]*")?\s*\))')
HREF_RE = re.compile(r'(href=")([^"]+)(")')
ROUTE_PREFIX_RE = re.compile(r'^(#?/?(?:[a-z]{2}/)?grammar/book/|#)')


def _rewrite_links(md, aliases, known):
    """Point links at old slugs (`](old)`, `href="old"`, `#/xx/grammar/book/old`) at the new one."""
    def fix(target):
        prefix = ''
        bare = target
        m = ROUTE_PREFIX_RE.match(target)
        if m:
            prefix, bare = m.group(1), target[m.end():]
        if bare in aliases and bare not in known:
            return prefix + aliases[bare]
        return target

    md = LINK_RE.sub(lambda m: m.group(1) + fix(m.group(2)) + m.group(3), md)
    md = HREF_RE.sub(lambda m: m.group(1) + fix(m.group(2)) + m.group(3), md)
    return md


def canonicalize(data, code, level_for=None, level_source=None, extra_meta=None):
    """Return grammar/1 data for `data` ({meta?, tree, content}).

    level_for(topic, part, chapter) supplies a level for topics without one.
    """
    old_meta = dict(data.get('meta') or {})
    old_aliases = dict(old_meta.get('aliases') or {})
    content_in = data['content']

    mapping = {}
    parts = []
    used_levels = set()
    for pi, part in enumerate(data['tree']['parts'], 1):
        pslug = 'p%d' % pi
        chapters = []
        for ci, chapter in enumerate(part.get('chapters') or [], 1):
            cslug = '%s/ch%02d' % (pslug, ci)
            topics = []
            for ti, topic in enumerate(chapter.get('topics') or [], 1):
                tslug = '%s/t%02d' % (cslug, ti)
                old = topic['slug']
                if old in mapping:
                    raise SystemExit('grammar_schema(%s): duplicate topic slug %r' % (code, old))
                if old not in content_in:
                    raise SystemExit('grammar_schema(%s): topic %r has no content' % (code, old))
                mapping[old] = tslug
                level = topic.get('level')
                if level not in CEFR and level_for:
                    level = level_for(topic, part, chapter)
                if level not in CEFR:
                    raise SystemExit('grammar_schema(%s): topic %r has no CEFR level' % (code, old))
                used_levels.add(level)
                topics.append({'title': topic['title'], 'slug': tslug, 'level': level})
            chapters.append({'title': chapter['title'], 'slug': cslug, 'topics': topics})
        parts.append({'title': part['title'], 'slug': pslug, 'chapters': chapters})

    orphans = sorted(set(content_in) - set(mapping))
    if orphans:
        raise SystemExit('grammar_schema(%s): content keys not in tree: %s' % (code, orphans[:5]))

    known = set(mapping.values())
    aliases = {}
    # earlier generations first (old -> mid -> new), then this generation
    for old, mid in old_aliases.items():
        target = mapping.get(mid, mid)
        if old != target and old not in known:
            aliases[old] = target
    for old, new in mapping.items():
        if old != new:
            aliases[old] = new
    dangling = sorted(a for a, t in aliases.items() if t not in known)
    if dangling:
        raise SystemExit('grammar_schema(%s): aliases point at missing topics: %s' % (code, dangling[:5]))

    content = {}
    for old, new in mapping.items():
        content[new] = _rewrite_links(content_in[old], aliases, known)

    facts = LANGS[code]
    meta = {
        'schema': 'grammar/1',
        'lang': code,
        'name': old_meta.get('name') or old_meta.get('title') or '',
        'title': old_meta.get('title') or '',
        'description': old_meta.get('description') or '',
        'count': len(mapping),
        'topicCount': len(mapping),
        'levels': [lv for lv in CEFR if lv in used_levels],
    }
    if level_source or old_meta.get('levelSource'):
        meta['levelSource'] = level_source or old_meta.get('levelSource')
    meta['builder'] = facts['builder']
    meta['sources'] = facts['sources']
    meta['licences'] = facts['licences']
    if extra_meta:
        meta.update(extra_meta)
    meta['aliases'] = dict(sorted(aliases.items(), key=lambda kv: (kv[1], kv[0])))
    return {'meta': meta, 'tree': {'parts': parts}, 'content': content}


def render(code, data, header=None):
    name = LANGS[code]['global']
    header = header if header is not None else LANGS[code]['header']
    meta = data['meta']
    aliases = meta['aliases']
    meta_wo = {k: v for k, v in meta.items() if k != 'aliases'}
    lines = list(header or [])
    lines.append('')
    lines.append('const %s = {' % name)
    meta_json = json.dumps(meta_wo, ensure_ascii=False)
    lines.append('"meta": ' + meta_json[:-1] + ', "aliases": {')
    items = list(aliases.items())
    for i, (old, new) in enumerate(items):
        lines.append('  %s: %s%s' % (json.dumps(old, ensure_ascii=False), json.dumps(new),
                                     ',' if i < len(items) - 1 else ''))
    lines.append('}},')
    lines.append('"tree": %s,' % json.dumps(data['tree'], ensure_ascii=False, indent=1))
    lines.append('"content": {')
    keys = list(data['content'].keys())
    for i, slug in enumerate(keys):
        lines.append('%s: %s%s' % (json.dumps(slug), json.dumps(data['content'][slug], ensure_ascii=False),
                                   ',' if i < len(keys) - 1 else ''))
    lines.append('}};')
    lines.append('')
    lines.append("if (typeof module !== 'undefined' && module.exports) {")
    lines.append('  module.exports = %s;' % name)
    lines.append('}')
    lines.append(register_footer('grammar', code, name))
    return '\n'.join(lines)


def write(code, data, header=None, path=None):
    path = path or os.path.join(ROOT, LANGS[code]['file'])
    text = render(code, data, header)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    return path

"""Shared writer for grammar/1 data files (docs/data-schema.md).

Every grammar book is emitted through `canonicalize()` + `write()`:

  * slugs are ASCII and positional: part `p<N>`, chapter `p<N>/ch<NN>`,
    topic `p<N>/ch<NN>/t<NN>` (1-based, in reading order);
  * every slug the topic had before is kept in `meta.aliases` (old -> new),
    composed with any aliases already in the file, so saved positions,
    deep links and course references keep resolving;
  * intra-content links that point at an old slug are rewritten;
  * every topic has a CEFR `level`; `meta.levels` and `meta.topicCount`
    are derived from the tree.

`canonicalize()` is idempotent: running it on its own output changes nothing.

Run `python3 scripts/canonicalize_grammar.py [it de en fr]` to re-canonicalize
the shipped files in place (the Italian and German files are their own source
of truth; English and French are regenerated by their builders, which call
this module).
"""


def strip_accents(text):
    return ''.join(c for c in unicodedata.normalize('NFD', text)
                   if unicodedata.category(c) != 'Mn')


def merge_attested(generated, attested):
    """Fold in a Lexique-attested spelling variant that differs only in accents.

    Verbiste ships the post-1990 spelling for the -éger family ("protègerai")
    while the corpus overwhelmingly has the traditional one ("protégerai").
    Both are correct, so both are accepted.  The extra variant only takes the
    lead when Verbiste's own form is unattested in the corpus; otherwise it is
    appended, so marginal variants ("eussé", used only in "eussé-je") never
    displace the citation form ("eusse").
    """
    if not attested:
        return generated
    extra = [a for a in sorted(attested)
             if a not in generated
             and any(strip_accents(a) == strip_accents(g) for g in generated)]
    if not extra:
        return generated
    if any(g in attested for g in generated):
        return generated + extra
    return extra + [g for g in generated if g not in extra]


def build_verb(conj, infinitive, base_infinitive, meta):
    """meta: dict(rank, frequency, corpusRank, english, chinese, auxiliary,
                  auxiliaryAlt, reflexive, aspirateH, model)"""
    raw, tpl, origin = conj.simple(base_infinitive)
    if raw is None:
        return None
    reflexive = meta['reflexive']
    auxiliary = meta['auxiliary']
    pp = conj.participles(raw)
    if (auxiliary == 'être' or reflexive) and pp['ms']:
        # être-conjugated participles must agree, and Verbiste sometimes ships
        # only the masculine singular (fu:ir -> "enfui").  Agreement is fully
        # regular: add -e / -s / -es, with no doubling after -s/-x/-e.
        ms = pp['ms']
        if not pp['fs']:
            pp['fs'] = ms if ms.endswith('e') else ms + 'e'
        if not pp['mp']:
            pp['mp'] = ms if ms.endswith(('s', 'x')) else ms + 's'
        if not pp['fp']:
            pp['fp'] = pp['fs'] if pp['fs'].endswith('s') else pp['fs'] + 's'
    lex = conj.lex_forms
    attested_pp = set(lex.get((base_infinitive, 'par:pas')) or ())
    attested_pp |= set(lex.get((pp['ms'], 'ADJ')) or ())
    if auxiliary != 'être' and not reflexive:
        # An intransitive avoir-verb has no agreeing participle: Verbiste emits
        # "dormie/dormis/dormies" and "plue/plues" mechanically and those are
        # not French.  Only the masculine singular is unconditionally safe, so
        # the agreement forms are kept exactly when the corpus attests them.
        for slot in ('fs', 'mp', 'fp'):
            if pp[slot] and pp[slot] not in attested_pp:
                pp[slot] = ''
    aux_raw = conj.aux_table(auxiliary)
    mask = conj.person_mask(raw)

    tenses = OrderedDict()

    def add_person(key, group, label, slots, apply_reflexive=True, lex_tag=None):
        built = OrderedDict()
        for idx, person in enumerate(PERSONS):
            alts = list(slots[idx]) if idx < len(slots) else []
            if lex_tag and alts:
                alts = merge_attested(
                    alts, lex.get((base_infinitive, '%s:%s' % (lex_tag, LEX_PERSON[idx]))))
            override = FORM_OVERRIDES.get((base_infinitive, key, person))
            if override is not None:
                alts = list(override)
            for x in (EXTRA_FORMS.get((base_infinitive, key), {}).get(person) or []):
                if x not in alts and alts:
                    alts.append(x)
            words = []
            for a in alts:
                w = a
                if reflexive and apply_reflexive:
                    w = reflexive_prefix(person, w)
                words.append(w)
            built[person] = join_alts(words)
        if not any(built.values()):
            return
        tenses[key] = OrderedDict([
            ('type', 'person'), ('group_label', group), ('tense_label', label),
            ('forms', built),
        ])

    def add_single(key, group, label, values):
        vals = [v for v in values if v]
        if not vals:
            return
        tenses[key] = OrderedDict([
            ('type', 'single'), ('group_label', group), ('tense_label', label),
            ('forms', vals),
        ])

    # --- simple tenses ----------------------------------------------------
    add_person('indicatif_present', 'Indicatif', 'Présent', raw['indicative.present'],
               lex_tag='ind:pre')
    add_person('indicatif_imparfait', 'Indicatif', 'Imparfait', raw['indicative.imperfect'],
               lex_tag='ind:imp')
    add_person('indicatif_passe_simple', 'Indicatif', 'Passé simple', raw['indicative.simple-past'],
               lex_tag='ind:pas')
    add_person('indicatif_futur_simple', 'Indicatif', 'Futur simple', raw['indicative.future'],
               lex_tag='ind:fut')
    add_person('conditionnel_present', 'Conditionnel', 'Présent', raw['conditional.present'],
               lex_tag='cnd:pre')
    add_person('subjonctif_present', 'Subjonctif', 'Présent', raw['subjunctive.present'],
               lex_tag='sub:pre')
    add_person('subjonctif_imparfait', 'Subjonctif', 'Imparfait', raw['subjunctive.imperfect'],
               lex_tag='sub:imp')

    # --- compound tenses --------------------------------------------------
    compounds = [
        ('indicatif_passe_compose', 'Indicatif', 'Passé composé', 'indicative.present'),
        ('indicatif_plus_que_parfait', 'Indicatif', 'Plus-que-parfait', 'indicative.imperfect'),
        ('indicatif_passe_anterieur', 'Indicatif', 'Passé antérieur', 'indicative.simple-past'),
        ('indicatif_futur_anterieur', 'Indicatif', 'Futur antérieur', 'indicative.future'),
        ('conditionnel_passe', 'Conditionnel', 'Passé', 'conditional.present'),
        ('subjonctif_passe', 'Subjonctif', 'Passé', 'subjunctive.present'),
        ('subjonctif_plus_que_parfait', 'Subjonctif', 'Plus-que-parfait', 'subjunctive.imperfect'),
    ]
    for key, group, label, aux_key in compounds:
        forms = conj.compound_person(aux_raw[aux_key], pp, auxiliary, reflexive, mask)
        if not any(forms.values()):
            continue
        tenses[key] = OrderedDict([
            ('type', 'person'), ('group_label', group), ('tense_label', label),
            ('forms', forms),
        ])

    # --- impératif --------------------------------------------------------
    imp = raw.get('imperative.imperative-present') or []
    imp_slots = [[], imp[0] if len(imp) > 0 else [], [],
                 imp[1] if len(imp) > 1 else [], imp[2] if len(imp) > 2 else [], []]
    if reflexive:
        suffix = {'tu': '-toi', 'nous': '-nous', 'vous': '-vous'}
        built = OrderedDict()
        for idx, person in enumerate(PERSONS):
            alts = imp_slots[idx]
            built[person] = join_alts([a + suffix[person] for a in alts]) if alts else ''
        if any(built.values()):
            tenses['imperatif_present'] = OrderedDict([
                ('type', 'person'), ('group_label', 'Impératif'), ('tense_label', 'Présent'),
                ('forms', built),
            ])
    else:
        add_person('imperatif_present', 'Impératif', 'Présent', imp_slots)
        aux_imp = aux_raw.get('imperative.imperative-present') or []
        aux_imp_slots = [[], aux_imp[0] if len(aux_imp) > 0 else [], [],
                         aux_imp[1] if len(aux_imp) > 1 else [],
                         aux_imp[2] if len(aux_imp) > 2 else [], []]
        built = OrderedDict()
        for idx, person in enumerate(PERSONS):
            alts = aux_imp_slots[idx]
            if not alts:
                built[PERSONS[idx]] = ''
                continue
            pps = (Conjugator.agreement_for(PERSONS[idx], pp) if auxiliary == 'être'
                   else ([pp['ms']] if pp['ms'] else []))
            built[PERSONS[idx]] = join_alts(['%s %s' % (a, p) for a in alts for p in pps])
        if any(built.values()) and tenses.get('imperatif_present'):
            tenses['imperatif_passe'] = OrderedDict([
                ('type', 'person'), ('group_label', 'Impératif'), ('tense_label', 'Passé'),
                ('forms', built),
            ])

    # --- non-finite -------------------------------------------------------
    pres_part = (raw.get('participle.present-participle') or [[]])
    pres_part = list(pres_part[0]) if pres_part else []
    for x in (EXTRA_FORMS.get((base_infinitive, 'participe_present'), {}).get('_') or []):
        if x not in pres_part:
            pres_part.insert(0, x)
    pres_part = merge_attested(pres_part, lex.get((base_infinitive, 'par:pre')))
    pp_values = []
    for a in pres_part:
        pp_values.append(reflexive_prefix('il_elle_on', a) if reflexive else a)
    add_single('participe_present', 'Participe', 'Présent', pp_values)

    ordered_pp = merge_attested([v for v in (pp['ms'], pp['fs'], pp['mp'], pp['fp']) if v],
                                attested_pp)
    add_single('participe_passe', 'Participe', 'Passé', list(OrderedDict.fromkeys(ordered_pp)))

    inf_present = infinitive
    add_single('infinitif_present', 'Infinitif', 'Présent', [inf_present])
    if auxiliary == 'être':
        pieces = ['être %s' % v for v in OrderedDict.fromkeys(
            [pp['ms'], pp['fs'], pp['mp'], pp['fp']]) if v]
    else:
        pieces = ['avoir %s' % pp['ms']] if pp['ms'] else []
    if reflexive:
        pieces = [reflexive_prefix('il_elle_on', p) for p in pieces]
    add_single('infinitif_passe', 'Infinitif', 'Passé', pieces)

    # --- impersonal verbs -------------------------------------------------
    # Verbiste runs "neiger" through the ordinary -ger model and happily emits
    # "je neige".  Wiktionary dashes those cells, and they are not French.
    # Blank them everywhere; the gap declaration below then records them.
    dead = IMPERSONAL.get(base_infinitive)
    if dead:
        for key, t in list(tenses.items()):
            if t['type'] != 'person':
                continue
            for person in dead:
                t['forms'][person] = ''
            if not any(t['forms'].values()):
                del tenses[key]

    # A verb with no past participle (renaître, poindre, bruire) is genuinely
    # defective: it simply has no compound tenses.  Keep it for its simple
    # tenses rather than dropping it, but insist on a usable paradigm.
    finite = sum(1 for t in tenses.values() if t['type'] == 'person')
    if len(tenses) < 3 or finite < 1:
        return None

    entry = OrderedDict()
    entry['rank'] = meta['rank']
    entry['infinitive'] = infinitive
    entry['frequency'] = meta['frequency']
    entry['corpusRank'] = meta['corpusRank']
    entry['english'] = meta['english']
    entry['chinese'] = meta['chinese']
    entry['partOfSpeech'] = 'verbe pronominal' if reflexive else 'verbe'
    entry['model'] = tpl
    entry['auxiliary'] = auxiliary
    if meta.get('auxiliaryAlt'):
        entry['auxiliaryAlt'] = meta['auxiliaryAlt']
    if reflexive:
        entry['reflexive'] = True
        entry['frequencyBasis'] = 'Lexique lemma frequency of the base verb "%s"' % base_infinitive
    if meta.get('aspirateH'):
        entry['aspirateH'] = True
    missing = [k for k in CANONICAL_TENSES if k not in tenses]
    if missing:
        # Declared, not silently absent: falloir has no plural, renaître has no
        # past participle, pouvoir has no imperative.  The validator checks that
        # a tense is missing only when it is listed here.
        entry['defective'] = missing
    gaps = OrderedDict()
    for key, t in tenses.items():
        if t['type'] != 'person':
            continue
        empty = [p for p in PERSONS if not t['forms'][p]]
        if key.startswith('imperatif'):
            empty = [p for p in empty if p in ('tu', 'nous', 'vous')]
        if empty:
            gaps[key] = empty
    if gaps:
        # Every person slot that is legitimately empty, declared per tense:
        # falloir is impersonal, clore has no "nous/vous" present, pleuvoir has
        # no plural past historic.  The validator refuses any undeclared hole.
        entry['gaps'] = gaps
    entry['participle'] = OrderedDict([('ms', pp['ms']), ('fs', pp['fs']),
                                       ('mp', pp['mp']), ('fp', pp['fp'])])
    entry['source'] = SOURCE_LABEL
    entry['tenses'] = tenses
    return entry


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', default='/tmp/frconj')
    ap.add_argument('--limit', type=int, default=1800)
    ap.add_argument('--refresh-cache', action='store_true')
    ap.add_argument('--out', default=OUT_PATH)
    args = ap.parse_args()

    work = args.work
    need = {
        'verbiste': os.path.join(work, 'verbiste-0.1.49', 'data'),
        'lexique': os.path.join(work, 'Lexique383.tsv'),
        'kaikki': os.path.join(work, 'fr-verbs.jsonl'),
        'ecdict': os.path.join(work, 'stardict.db'),
    }
    for label, path in need.items():
        if not os.path.exists(path):
            sys.exit('missing %s at %s\nDownload:%s' % (label, path, DOWNLOADS))

    templates = parse_templates(os.path.join(need['verbiste'], 'conjugation-fr.xml'))
    verb_templates, aspirate = parse_verbs(os.path.join(need['verbiste'], 'verbs-fr.xml'))
    print('verbiste: %d model paradigms, %d infinitives' % (len(templates), len(verb_templates)))

    freq, lex_forms = load_lexique(need['lexique'])
    ordered = sorted(freq.items(), key=lambda kv: (-kv[1], kv[0]))
    corpus_rank = {lemma: i + 1 for i, (lemma, _f) in enumerate(ordered)}
    print('lexique: %d verb lemmas, %d (lemma, morph-tag) attestations'
          % (len(ordered), len(lex_forms)))

    conj = Conjugator(templates, verb_templates, aspirate, lex_forms)

    candidates = []
    for lemma, f in ordered:
        tpl, origin = template_for(lemma, verb_templates)
        if tpl:
            candidates.append((lemma, f, origin))
    print('conjugatable candidates: %d' % len(candidates))

    wanted = set(l for l, _f, _o in candidates[:args.limit * 3])
    wanted |= {'avoir', 'être'}
    wanted |= set(base for _s, base, _e, _c in PRONOMINAL_VERBS)
    kaikki = load_kaikki(need['kaikki'], os.path.join(work, 'fr-verb-kaikki-cache.json'),
                         wanted, refresh=args.refresh_cache)
    print('kaikki records for candidates: %d' % len(kaikki))

    db = sqlite3.connect(need['ecdict'])
    cur = db.cursor()
    zh_cache = {}

    stats = Counter()
    picked = []
    rejects = []

    def try_build(lemma, f):
        """Run the quality gate; return an entry or None (and log why)."""
        rec = kaikki.get(lemma)
        if not rec:
            if lemma not in MANUAL_ENGLISH:
                stats['no_wiktionary_entry'] += 1
                rejects.append((lemma, 'no_wiktionary_entry'))
                return None
            rec = {'glosses': [], 'aux': None, 'forms': []}
        english = MANUAL_ENGLISH.get(lemma) or clean_english(rec['glosses'])
        if bad_text(english) or len(english) < 2:
            stats['no_english_gloss'] += 1
            rejects.append((lemma, 'no_english_gloss'))
            return None
        if english.strip().lower() == lemma.lower():
            stats['gloss_is_headword'] += 1
            rejects.append((lemma, 'gloss_is_headword'))
            return None
        chinese = MANUAL_CHINESE.get(lemma) or MANUAL_ENGLISH_ZH.get(lemma)
        if not chinese:
            for key in english_pivot_keys(rec['glosses']):
                chinese = ecdict_chinese(cur, zh_cache, key)
                if chinese:
                    break
        if not chinese or bad_text(chinese) or not CJK.search(chinese):
            stats['no_chinese_gloss'] += 1
            rejects.append((lemma, 'no_chinese_gloss'))
            return None
        aux, aux_alt = choose_auxiliary(lemma, rec)
        meta = {
            'rank': 0, 'frequency': f, 'corpusRank': corpus_rank[lemma],
            'english': english, 'chinese': chinese, 'auxiliary': aux,
            'auxiliaryAlt': aux_alt, 'reflexive': False,
            'aspirateH': bool(aspirate.get(lemma)),
        }
        entry = build_verb(conj, lemma, lemma, meta)
        if entry is None:
            stats['conjugation_failed'] += 1
            rejects.append((lemma, 'conjugation_failed'))
            return None
        return entry

    for lemma, f, origin in candidates:
        if len(picked) >= args.limit:
            break
        if lemma in PRONOMINAL_ONLY:
            stats['skipped_pronominal_only'] += 1
            continue
        entry = try_build(lemma, f)
        if entry is None:
            continue
        picked.append(entry)
        stats['accepted'] += 1
        stats['origin_' + origin] += 1

    # --- model-paradigm supplement ---------------------------------------
    # Pure corpus frequency leaves ~47 of Verbiste's 148 model paradigms with
    # no representative (moudre, éclore, prévaloir, ...).  A conjugation
    # trainer should be able to show every Bescherelle pattern, so for each
    # still-uncovered model we add exactly one verb: its most frequent member,
    # and only if it clears the same gloss gate.  Nothing is added to hit a
    # count -- the supplement stops as soon as every model has a representative.
    picked_names = set(e['infinitive'] for e in picked)
    covered = set()
    # pronominal entries are appended below but already cover their base model
    for lemma in picked_names | set(b for _s, b, _e, _c in PRONOMINAL_VERBS):
        tpl, _ = template_for(lemma, verb_templates)
        if tpl:
            covered.add(tpl)
    for lemma, f, origin in candidates:
        if lemma in picked_names or lemma in PRONOMINAL_ONLY:
            continue
        tpl, _ = template_for(lemma, verb_templates)
        if not tpl or tpl in covered:
            continue
        entry = try_build(lemma, f)
        if entry is None:
            continue
        covered.add(tpl)
        picked.append(entry)
        picked_names.add(lemma)
        stats['accepted_model_coverage'] += 1

    # --- pronominal verbs -------------------------------------------------
    for surface, base, en, zh in PRONOMINAL_VERBS:
        tpl, origin = template_for(base, verb_templates)
        if not tpl:
            stats['pronominal_no_template'] += 1
            continue
        meta = {
            'rank': 0,
            'frequency': freq.get(base, 0.0),
            'corpusRank': corpus_rank.get(base, 0),
            'english': en, 'chinese': zh,
            'auxiliary': 'être', 'auxiliaryAlt': None, 'reflexive': True,
            'aspirateH': bool(aspirate.get(base)),
        }
        entry = build_verb(conj, surface, base, meta)
        if entry is None:
            stats['pronominal_failed'] += 1
            continue
        picked.append(entry)
        stats['accepted_pronominal'] += 1

    # rank = position in this dataset ordered by real corpus frequency
    picked.sort(key=lambda e: (-e['frequency'], e['infinitive']))
    seen = set()
    unique = []
    for e in picked:
        if e['infinitive'] in seen:
            continue
        seen.add(e['infinitive'])
        unique.append(e)
    for i, e in enumerate(unique):
        e['rank'] = i + 1
    picked = unique

    total_forms = 0
    for e in picked:
        for t in e['tenses'].values():
            vals = t['forms'].values() if isinstance(t['forms'], dict) else t['forms']
            total_forms += sum(1 for v in vals if v)

    header = (
        '// French conjugation dataset — auto-generated by\n'
        '// scripts/build_french_conjugations.py.  DO NOT EDIT BY HAND.\n'
        '//\n'
        '// Verbs: %d   Tense/mood groups: up to %d   Non-empty forms: %d\n'
        '//\n'
        '// Sources and licences:\n'
        '//   * Verbiste 0.1.49 conjugation templates — GPL-2+ (Pierre Sarrazin)\n'
        '//   * Lexique 3.83 lemma frequencies — CC BY-SA 4.0 (lexique.org)\n'
        '//   * English Wiktionary via Wiktextract/kaikki.org — CC BY-SA 4.0 / GFDL\n'
        '//     (English glosses + auxiliary selection + cross-validation forms)\n'
        '//   * ECDICT 1.0.28 — English→Chinese pivot for the Chinese gloss\n'
        '//\n'
        '// Subject-pronoun elision is NOT baked in: "ai" is stored under the "je"\n'
        '// key and the app renders "j\'ai".  `aspirateH: true` marks verbs whose\n'
        '// initial h blocks elision (je hais).  Reflexive-pronoun elision\n'
        '// ("m\'appelle") is part of the form and IS stored.\n'
        % (len(picked), max(len(e['tenses']) for e in picked), total_forms)
    )

    body = json.dumps(picked, ensure_ascii=False, separators=(',', ':'))
    js = (header +
          '\n(function () {\n  \'use strict\';\n\n'
          '  const FRENCH_CONJUGATION_DATA = ' + body + ';\n\n'
          '  if (typeof window !== \'undefined\') {\n'
          '    window.FRENCH_CONJUGATION_DATA = FRENCH_CONJUGATION_DATA;\n  }\n\n'
          '  if (typeof module !== \'undefined\' && module.exports) {\n'
          '    module.exports = FRENCH_CONJUGATION_DATA;\n  }\n})();\n')
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(js)

    print('wrote %s (%.1f MB)' % (args.out, os.path.getsize(args.out) / 1e6))
    print('verbs: %d, non-empty forms: %d' % (len(picked), total_forms))
    print('stats:', dict(sorted(stats.items())))
    aux_counter = Counter(e['auxiliary'] for e in picked)
    print('auxiliary distribution:', dict(aux_counter))
    tense_counter = Counter(len(e['tenses']) for e in picked)
    print('tense-group counts:', dict(sorted(tense_counter.items())))
    models = set()
    for e in picked:
        models.update(e['model'].split(' + '))
    print('model paradigms represented: %d of %d' % (len(models), len(templates)))
    print('rejected candidates: %d -> %s' % (len(rejects), rejects))

    # side-car report used by the validator for cross-checking
    with open(os.path.join(work, 'build-report.json'), 'w', encoding='utf-8') as f:
        json.dump({'stats': dict(stats), 'verbs': len(picked), 'forms': total_forms,
                   'models': len(models), 'rejects': rejects},
                  f, ensure_ascii=False, indent=1)


if __name__ == '__main__':
    main()

def bad_text(value):
    if not value or not str(value).strip():
        return 'empty'
    v = str(value).strip()
    if MOJIBAKE.search(v):
        return 'mojibake'
    if PLACEHOLDER.match(v):
        return 'placeholder'
    if re.search(r'(.{3,}?)\1{2,}', v):
        return 'repetition'
    return None



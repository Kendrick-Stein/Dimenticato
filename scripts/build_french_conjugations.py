def parse_templates(path):
    """conjugation-fr.xml -> {template_name: {tense_key: [ [alt, ...], ... ]}}"""
    root = ET.parse(path).getroot()
    templates = {}
    for tpl in root:
        name = tpl.get('name')
        table = {}
        for section in tpl:
            for tense in section:
                key = '%s.%s' % (section.tag, tense.tag)
                slots = []
                for p in tense:
                    # <p/> with no <i> child = the verb has no form here
                    # (defective).  <p><i/></p> means "stem + empty ending",
                    # which is a real form: "il bat", "il vêt", "nui".
                    alts = [(i.text or '').strip() for i in p]
                    slots.append(alts if len(p) else [])
                table[key] = slots
        templates[name] = table
    return templates


def parse_verbs(path):
    """verbs-fr.xml -> ({infinitive: template}, {infinitive: aspirate_h})"""
    root = ET.parse(path).getroot()
    mapping = OrderedDict()
    aspirate = {}
    for v in root:
        inf = (v.find('i').text or '').strip()
        tpl = (v.find('t').text or '').strip()
        if not inf or not tpl:
            continue
        mapping[inf] = tpl
        if v.find('aspirate-h') is not None:
            aspirate[inf] = True
    return mapping, aspirate



def load_lexique(path):
    """Return (lemma -> frequency, (lemma, morph-tag) -> set(attested surface forms)).

    Adjective rows are indexed too, under the key (adjective-lemma, 'ADJ').  A
    past participle that has become an adjective ("résolu") is filed in Lexique
    under cgram=ADJ, so its feminine/plural agreement forms ("résolue",
    "résolues") never appear in the VER rows; without this they would look
    unattested and get dropped.
    """
    import csv
    freq = OrderedDict()
    forms = {}
    with open(path, encoding='utf-8') as f:
        for row in csv.DictReader(f, delimiter='\t'):
            if row['cgram'] == 'ADJ':
                forms.setdefault((row['lemme'], 'ADJ'), set()).add(row['ortho'])
                continue
            if row['cgram'] != 'VER':
                continue
            lemma = row['lemme']
            if lemma not in freq:
                try:
                    freq[lemma] = round(float(row['freqlemfilms2']) + float(row['freqlemlivres']), 2)
                except ValueError:
                    freq[lemma] = 0.0
            for tag in row['infover'].split(';'):
                tag = tag.strip()
                if tag:
                    forms.setdefault((lemma, tag), set()).add(row['ortho'])
    return freq, forms


def load_kaikki(path, cache_path, wanted, refresh=False):
    if os.path.exists(cache_path) and not refresh:
        with open(cache_path, encoding='utf-8') as f:
            return json.load(f)
    records = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            if '"pos": "verb"' not in line:
                continue
            try:
                d = json.loads(line)
            except Exception:
                continue
            if d.get('lang_code') != 'fr' or d.get('pos') != 'verb':
                continue
            word = d.get('word')
            if word not in wanted:
                continue
            head_args = set()
            for h in (d.get('head_templates') or []):
                for v in (h.get('args') or {}).values():
                    head_args.add(str(v))
            if 'verb form' in head_args:
                continue
            glosses = []
            tags = set()
            for s in d.get('senses', []):
                if s.get('form_of') or s.get('alt_of'):
                    continue
                st = set(s.get('tags') or [])
                if st & {'form-of', 'obsolete', 'archaic'}:
                    continue
                tags |= st
                for g in (s.get('glosses') or []):
                    g = g.strip()
                    if g and g not in glosses:
                        glosses.append(g)
            aux = set()
            wforms = {}
            for fm in (d.get('forms') or []):
                form = (fm.get('form') or '').strip()
                ftags = fm.get('tags') or []
                if 'multiword-construction' in ftags and 'infinitive' in ftags:
                    if form.startswith('être'):
                        aux.add('être')
                    elif form.startswith('avoir'):
                        aux.add('avoir')
                if fm.get('source') == 'conjugation' and form and 'table-tags' not in ftags:
                    wforms.setdefault('|'.join(sorted(ftags)), []).append(form)
            rec = records.setdefault(word, {'glosses': [], 'aux': [], 'tags': [], 'forms': {}})
            for g in glosses:
                if g not in rec['glosses']:
                    rec['glosses'].append(g)
            rec['aux'] = sorted(set(rec['aux']) | aux)
            rec['tags'] = sorted(set(rec['tags']) | tags)
            for k, v in wforms.items():
                rec['forms'].setdefault(k, [])
                for item in v:
                    if item not in rec['forms'][k]:
                        rec['forms'][k].append(item)
    with open(cache_path, 'w', encoding='utf-8') as f:
        json.dump(records, f, ensure_ascii=False)
    return records


def choose_auxiliary(inf, rec):
    """Return (auxiliary, alternative_or_None)."""
    aux = set(rec.get('aux') or []) if rec else set()
    if aux == {'être'}:
        return 'être', None
    if aux == {'avoir', 'être'}:
        if inf in ETRE_PREFERRED_FOR_DUAL:
            return 'être', 'avoir'
        return 'avoir', 'être'
    if aux == {'avoir'}:
        if inf in ETRE_PREFERRED_FOR_DUAL:
            return 'être', 'avoir'
        return 'avoir', None
    # No Wiktionary evidence — fall back to the closed être class.
    if inf in ETRE_PREFERRED_FOR_DUAL:
        return 'être', 'avoir'
    return 'avoir', None


class Conjugator(object):
    def __init__(self, templates, verb_templates, aspirate, lex_forms=None):
        self.templates = templates
        self.verb_templates = verb_templates
        self.aspirate = aspirate
        self.lex_forms = lex_forms or {}
        self.aux_tables = {}

    def simple(self, infinitive):
        tpl, origin = template_for(infinitive, self.verb_templates)
        if not tpl:
            return None, None, None
        raw = apply_template(infinitive, tpl, self.templates)
        variant = VARIANT_INFINITIVES.get(infinitive)
        if variant:
            vtpl, _o = template_for(variant, self.verb_templates)
            if vtpl:
                vraw = apply_template(variant, vtpl, self.templates)
                for key, slots in vraw.items():
                    base = raw.get(key) or []
                    merged = []
                    for i in range(max(len(base), len(slots))):
                        a = list(base[i]) if i < len(base) else []
                        for x in (slots[i] if i < len(slots) else []):
                            if x not in a:
                                a.append(x)
                        merged.append(a)
                    raw[key] = merged
                tpl = '%s + %s' % (tpl, vtpl)
        return raw, tpl, origin

    def aux_table(self, aux):
        if aux not in self.aux_tables:
            raw, _tpl, _o = self.simple(aux)
            self.aux_tables[aux] = raw
        return self.aux_tables[aux]

    # -- helpers ------------------------------------------------------------
    @staticmethod
    def participles(raw):
        slots = raw.get('participle.past-participle') or []
        def pick(i):
            return slots[i][0] if i < len(slots) and slots[i] else ''
        ms, mp, fs, fp = pick(0), pick(1), pick(2), pick(3)
        return {'ms': ms, 'fs': fs, 'mp': mp, 'fp': fp}

    @staticmethod
    def agreement_for(person, pp):
        if person in ('je', 'tu', 'il_elle_on'):
            cand = [pp['ms'], pp['fs']]
        elif person == 'nous':
            cand = [pp['mp'], pp['fp']]
        elif person == 'ils_elles':
            cand = [pp['mp'], pp['fp']]
        else:  # vous: polite singular or plural, either gender
            cand = [pp['ms'], pp['fs'], pp['mp'], pp['fp']]
        return [c for c in cand if c]

    @staticmethod
    def person_mask(raw):
        """Which persons this verb has at all (impersonal verbs only have il)."""
        mask = [False] * 6
        for key in ('indicative.present', 'indicative.imperfect', 'indicative.future',
                    'indicative.simple-past', 'conditional.present',
                    'subjunctive.present', 'subjunctive.imperfect'):
            for idx, alts in enumerate(raw.get(key) or []):
                if idx < 6 and alts:
                    mask[idx] = True
        return mask

    def compound_person(self, aux_slots, pp, auxiliary, reflexive, mask=None):
        """aux_slots: 6 alternative-lists of the auxiliary's simple tense."""
        forms = OrderedDict()
        for idx, person in enumerate(PERSONS):
            aux_alts = aux_slots[idx] if idx < len(aux_slots) else []
            if mask is not None and not mask[idx]:
                forms[person] = ''
                continue
            if not aux_alts:
                forms[person] = ''
                continue
            pieces = []
            if auxiliary == 'être':
                pps = self.agreement_for(person, pp)
            else:
                pps = [pp['ms']] if pp['ms'] else []
            for a in aux_alts:
                for participle in pps:
                    phrase = '%s %s' % (a, participle)
                    if reflexive:
                        phrase = reflexive_prefix(person, phrase)
                    pieces.append(phrase)
            forms[person] = join_alts(pieces)
        return forms



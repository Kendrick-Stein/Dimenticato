def template_for(inf, mapping):
    """Verbiste template, falling back to prefix stripping (refaire -> faire)."""
    if inf in mapping:
        return mapping[inf], 'verbiste'
    for pref in PREFIXES:
        if inf.startswith(pref) and len(inf) > len(pref) + 3:
            base = inf[len(pref):]
            if base in mapping:
                return mapping[base], 'verbiste+prefix'
    return None, None


